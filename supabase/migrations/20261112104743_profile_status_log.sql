-- Profil statusu dəyişikliklərinin jurnalı (kim təsdiq/rədd etdi).
create table if not exists public.profile_status_log (
  id bigint generated by default as identity primary key,
  profile_id uuid not null,
  old_status text,
  new_status text not null,
  changed_by uuid,
  changed_by_email text,
  changed_at timestamptz not null default now()
);
alter table public.profile_status_log enable row level security;

drop policy if exists profile_status_log_admin_read on public.profile_status_log;
create policy profile_status_log_admin_read on public.profile_status_log
  for select using (public.is_admin());

create or replace function public.log_profile_status_change()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  if new.status is distinct from old.status then
    insert into public.profile_status_log (profile_id, old_status, new_status, changed_by, changed_by_email)
    values (new.id, old.status, new.status, auth.uid(),
            (select p.email from public.profiles p where p.id = auth.uid()));
  end if;
  return new;
end;
$function$;

drop trigger if exists profiles_log_status on public.profiles;
create trigger profiles_log_status
  after update of status on public.profiles
  for each row execute function public.log_profile_status_change();
